# Values that identify someone on their own; the re-appearance scan looks for these.
DIRECT_ROLES = {"name", "first_name", "last_name", "email", "phone", "address", "id", "financial", "secret", "network"}
DIRECT_CATEGORIES = {"PERSON", "CONTACT", "ID", "FINANCIAL", "CREDENTIAL", "NETWORK"}
QUASI_ROLES = ("sex", "age", "dob", "state", "city", "zip")
QUASI_HEADERS = ("education", "occupation")
DATE_LABELS = ("date",)          # birth dates are regenerated by design, not shifted
MIN_LEN = 4                      # shorter values ('A1', 'Bo') match by accident too often to scan
MIN_PART = 4                     # shortest name part / local part searched for partially
KEPT_SHARE = 0.9                 # a quasi column counts as kept when this share of rows is unchanged
JOIN_OVERLAP = 0.5               # share of one id column's values found in another to call it a join
CATEGORICAL_MAX = 50             # distinct values above which a kept text column is not compared
WORD = re.compile(r"[^\W_]+")
DIGIT_RUN = re.compile(r"\d(?:[\s().-]{0,2}\d)+")
K_BUCKETS = (("1", 1, 1), ("2-4", 2, 4), ("5-9", 5, 9), ("10+", 10, None))


@dataclass
class Run:
    """What the metrics see: the inputs, the masked rows, the audit and the roles used."""

    sources: list            # `sources.Source`, original rows
    out: dict[str, list[dict]]
    mentions: list           # `api.Mention`: where each value was and is (offsets, never values)
    roles: dict[str, dict[str, str]]

    def original(self, m) -> str:
        """The original text a mention replaced (the cell, or the span within it)."""
        return _cell(self.by_name[m.source].rows[m.row].get(m.column), m.start, m.end)

    def masked(self, m) -> str:
        """What the output holds where the mention was: read from the output, not from the audit."""
        return _cell(self.out[m.source][m.row].get(m.column), m.out_start, m.out_end)

    def __post_init__(self):
        self.by_name = {s.name: s for s in self.sources}


def _cell(value: object, start: int | None = None, end: int | None = None) -> str:
    text = "" if missing(value) else str(value)
    return text if start is None else text[start:end]


def _share(a: float, b: float) -> float | None:
    return round(a / b, 4) if b else None


def _where(source: str, row: int, column: str) -> dict:
    return {"source": source, "row": row, "column": column}


def _direct(m) -> bool:
    if m.start is None:
        return m.label in DIRECT_ROLES
    return m.category in DIRECT_CATEGORIES or (m.category == "ADDRESS" and m.label not in ("zip", "place"))


# -- privacy: original re-appearance ----------------------------------------------------------------

class _Output:
    """Every output cell as one searchable string, with a way back from an offset to its cell."""

    def __init__(self, run: Run):
        self.cells: list[tuple[str, int, str]] = []
        texts, starts, pos = [], [], 0
        for src in run.sources:
            for i, row in enumerate(run.out[src.name]):
                for col, value in row.items():
                    text = _cell(value)
                    if not text:
                        continue
                    self.cells.append((src.name, i, col))
                    texts.append(text)
                    starts.append(pos)
                    pos += len(text) + 1
        self.starts = starts
        self.raw = "\n".join(texts)
        # Lower-cased cell by cell, keeping offsets where lowering would change a cell's length.
        self.low = "\n".join(t.lower() if len(t.lower()) == len(t) else t for t in texts)
        # Each cell's words, space-separated and space-padded; cells are joined by a double space,
        # which no multi-word needle can span.
        words = [" " + " ".join(WORD.findall(t.casefold())) + " " for t in texts]
        self.word_starts = [0]
        for w in words[:-1]:
            self.word_starts.append(self.word_starts[-1] + len(w))
        self.words = "".join(words)
        self.digits = [(c, re.sub(r"\D", "", m.group())) for c, t in enumerate(texts) for m in DIGIT_RUN.finditer(t)]
        # Spans maskara itself wrote, per cell: a persona surname there is synthetic, not a leftover.
        index = {cell: c for c, cell in enumerate(self.cells)}
        self.written: dict[int, list[tuple[int, int]]] = defaultdict(list)
        for m in run.mentions:
            c = index.get((m.source, m.row, m.column))
            if c is None or not m.changed:
                continue
            span = (0, len(texts[c])) if m.out_start is None else (m.out_start, m.out_end)
            self.written[c].append(span)

    def cell_at(self, pos: int) -> tuple[int, int]:
        c = bisect_right(self.starts, pos) - 1
        return c, pos - self.starts[c]

    def find(self, blob: str, needle: str) -> Iterable[int]:
        """Offsets of `needle` in `blob` that do not start or end inside a longer word."""
        start = blob.find(needle)
        while start >= 0:
            end = start + len(needle)
            if not (start and blob[start - 1].isalnum() and needle[0].isalnum()) and \
                    not (end < len(blob) and blob[end].isalnum() and needle[-1].isalnum()):
                yield start
            start = blob.find(needle, start + 1)

    def in_written(self, c: int, start: int, end: int) -> bool:
        return any(a <= start and end <= b for a, b in self.written.get(c, ()))


def _forms(value: str, m) -> dict[str, list]:
    """How to look for one original: exact strings, normalized word sequences / digits, and parts."""
    words = WORD.findall(value.casefold())
    digits = re.sub(r"\D", "", value)
    person = m.category == "PERSON" or m.label in ("name", "first_name", "last_name")
    email = "@" in value and (m.category == "CONTACT" or m.label == "email")
    if person and len(words) < 2:  # a lone first or last name: too common to call a leak on its own
        return {"exact": [], "normalized": [], "digits": [], "partial": [w for w in words if len(w) >= MIN_PART]}
    if digits and len(digits) < 7 and not re.sub(r"[\d\s().-]", "", value):  # a card's last four, a year
        return {"exact": [], "normalized": [], "digits": [], "partial": [digits]}
    forms: dict[str, list] = {"exact": [value.strip()], "normalized": [" ".join(words)], "digits": [], "partial": []}
    if person:
        forms["normalized"].append(" ".join(words[-1:] + words[:-1]))  # 'Lopez, Maria'
        forms["partial"] = [words[-1]] if len(words[-1]) >= MIN_PART else []
    elif email:
        local = re.sub(r"[^a-z0-9]", "", value.split("@", 1)[0].casefold())
        forms["partial"] = [local] if len(local) > MIN_PART else []
    elif len(digits) >= 7:
        forms["digits"] = [digits[-10:]] if m.label == "phone" or m.category == "CONTACT" else [digits]
        if m.label == "phone":
            forms["partial"] = [digits[-7:]]
    elif m.category == "ADDRESS" or m.label == "address":
        street = " ".join(w for w in words if not w.isdigit())
        forms["partial"] = [street] if len(street) >= 8 else []
    return forms


def reappearance(run: Run) -> dict:
    """Search the whole output for every original direct identifier the run knew about.

    exact       the original string, case and punctuation as written
    normalized  the same words ignoring case, punctuation and spacing ('lopez, maria' for a name),
                or the same digits in any layout (phones, card and account numbers)
    partial     a surname, an email's local part, a phone's last seven digits, a street name, a lone
                first or last name, a short number (a card's last four), anywhere outside text maskara
                wrote itself (so a persona who happens to share a surname is not counted)
    Each original value counts once, at its strongest level.
    """
    output = _Output(run)
    seen: dict[str, object] = {}
    short = 0
    for m in run.mentions:
        if not _direct(m):
            continue
        value = run.original(m).strip()
        key = " ".join(WORD.findall(value.casefold()))
        if not key or key in seen:
            continue
        if len(value) < MIN_LEN:
            short += 1
            seen[key] = None
            continue
        seen[key] = (value, m)

    found = Counter()
    by_category: Counter = Counter()
    hits = []
    for entry in seen.values():
        if entry is None:
            continue
        value, m = entry
        forms = _forms(value, m)
        hit = _first_hit(output, forms)
        if hit is None:
            continue
        level, c = hit
        found[level] += 1
        by_category[m.category] += 1
        if len(hits) < 100:
            hits.append({"level": level, "category": m.category, "label": m.label,
                         "found_in": _where(*output.cells[c]), "original_at": _where(m.source, m.row, m.column)})
    scanned = sum(e is not None for e in seen.values())
    return {
        "measured": f"{scanned} distinct original direct identifiers (names, emails, phones, street lines, ids, "
                    "account numbers) that column roles or detectors found, searched for anywhere in the output: "
                    "exact, normalized (case, punctuation, digit layout) and partial (surname, email local part, "
                    "last seven phone digits, street name, lone first or last name, short numbers such as a card's "
                    "last four)",
        "not_measured": f"values no detector or column role found are not known, so not searched for; "
                        f"{short} values shorter than {MIN_LEN} characters were skipped; dates, ages, cities, "
                        "states and ZIPs are quasi-identifiers, covered by k-anonymity instead",
        "scanned": scanned, "skipped_short": short,
        "exact": found["exact"], "normalized": found["normalized"], "partial": found["partial"],
        "found": found["exact"] + found["normalized"],
        "by_category": dict(sorted(by_category.items())), "hits": hits,
    }


def _first_hit(output: _Output, forms: dict[str, list]) -> tuple[str, int] | None:
    for needle in forms["exact"]:
        for pos in output.find(output.raw, needle):
            return "exact", output.cell_at(pos)[0]
    for needle in forms["normalized"]:
        if needle and (pos := output.words.find(f" {needle} ")) >= 0:
            return "normalized", bisect_right(output.word_starts, pos) - 1
    for needle in forms["digits"]:
        for c, digits in output.digits:
            if needle in digits:
                return "normalized", c
    for needle in forms["partial"]:
        blob = output.raw if needle.isdigit() else output.low
        for pos in output.find(blob, needle):
            c, at = output.cell_at(pos)
            if not output.in_written(c, at, at + len(needle)):
                return "partial", c
    return None


# -- privacy: quasi-identifiers ---------------------------------------------------------------------

def _quasi_value(role: str, value: object) -> object:
    if missing(value):
        return None
    text = str(value).strip()
    if role == "dob":
        day = parse_date(text)
        return day.year if day else None
    if role == "zip":
        return text[:5]
    return text.casefold()


def _k(keys: list[tuple]) -> list[int]:
    counts = Counter(keys)
    return [counts[k] for k in keys]


def quasi_identifiers(run: Run) -> dict:
    tables = {}
    for src in run.sources:
        if src.kind != "table":
            continue
        roles = run.roles[src.name]
        cols = [c for c, r in roles.items() if r in QUASI_ROLES or (r == "keep" and c.lower() in QUASI_HEADERS)]
        if not cols:
            continue
        role = {c: "dob" if roles[c] == "dob" else roles[c] for c in cols}
        before = [tuple(_quasi_value(role[c], r.get(c)) for c in cols) for r in src.rows]
        after = [tuple(_quasi_value(role[c], r.get(c)) for c in cols) for r in run.out[src.name]]
        n = len(before)
        kept = [c for j, c in enumerate(cols)
                if n and sum(b[j] == a[j] for b, a in zip(before, after)) >= KEPT_SHARE * n]
        entry = {"columns": cols, "kept": kept, "rows": n}
        if kept:
            idx = [cols.index(c) for c in kept]
            ks = _k([tuple(a[j] for j in idx) for a in after])
            entry.update(unique=ks.count(1), unique_share=_share(ks.count(1), n), min_k=min(ks),
                         k={label: sum(lo <= k and (hi is None or k <= hi) for k in ks) for label, lo, hi in K_BUCKETS})
        # Linkage: an attacker who knows a person's original quasi values looks them up in the output.
        index = defaultdict(list)
        for i, a in enumerate(after):
            index[a].append(i)
        hits = sum(index.get(b) == [i] for i, b in enumerate(before))
        entry["linkage"] = {"columns": cols, "attempted": n, "reidentified": hits, "rate": _share(hits, n)}
        tables[src.name] = entry
    return {
        "measured": "per table: how many rows share their combination of the quasi-identifier columns the "
                    f"preset kept (unchanged in at least {KEPT_SHARE:.0%} of rows), as a k-anonymity distribution; "
                    "and a linkage attack that looks each person's original quasi values up in the output, "
                    "counting a re-identification when exactly their own row matches",
        "not_measured": "quasi-identifiers in free text (job titles, employers, events) and in columns left as "
                        "'keep' other than education and occupation; combinations across tables; an attacker "
                        "with outside data beyond the original quasi values",
        "tables": tables,
    }


def detections(run: Run) -> dict:
    changed = [m for m in run.mentions if m.changed]
    unlinked = [m for m in run.mentions if m.category in PERSON_BOUND and m.persona is None]
    pending = [m for m in run.mentions if m.resolution in ("ambiguous", "unresolved", "provisional")]
    return {
        "replaced": len(changed), "kept_by_policy": len(run.mentions) - len(changed),
        "by_category": dict(sorted(Counter(m.category for m in changed).items())),
        "by_detector": dict(sorted(Counter(m.detector for m in changed).items())),
        "by_link": dict(sorted(Counter(m.link for m in run.mentions).items())),
        "identity": {
            "by_resolution": dict(sorted(Counter(m.resolution for m in run.mentions).items())),
            "review_mentions": len(pending),
            "by_reason": dict(sorted(Counter(reason for m in pending for reason in m.evidence).items())),
            "measured": "Ownership decisions and review workload. Ambiguous/unresolved values use value-based "
                        "replacement; provisional names are grouped only within a document. See review.json.",
            "not_measured": "Identity accuracy needs gold owners; these are evidence states, not calibrated "
                            "probabilities. Replacement equality does not establish person identity.",
        },
        "unlinked": {
            "mentions": len(unlinked), "by_category": dict(sorted(Counter(m.category for m in unlinked).items())),
            "measured": "person-bound values (names, contacts, addresses, places, dates) no known person could "
                        "be found for; each got a persona keyed on the value itself, so it is replaced but not "
                        "tied to the right person's other records",
        },
        "measured": "every value replaced or kept by policy, by category, detector and how its owner was found",
        "not_measured": "detection recall and precision need gold labels: run `maskara bench`",
    }


# -- fidelity ---------------------------------------------------------------------------------------

def schema(run: Run) -> dict:
    tables = {}
    for src in run.sources:
        rows = run.out[src.name]
        columns = list(dict.fromkeys(c for r in rows for c in r))
        tables[src.name] = {"rows_before": len(src.rows), "rows_after": len(rows),
                            "columns_same": columns == src.columns}
    ok = all(t["rows_before"] == t["rows_after"] and t["columns_same"] for t in tables.values())
    return {"ok": ok, "tables": tables, "measured": "row counts and column names and order, per input"}


def joins(run: Run) -> dict:
    """Joins on id columns that worked before masking and what became of them.

    Two id columns of different inputs join when at least half of one's distinct values occur in the
    other. For every row whose original value joined, the masked value must reach exactly the same
    rows on the other side; one that reaches other rows (or none) is broken. A masked value that
    joins where the original did not is spurious.
    """
    cols = [(s.name, c) for s in run.sources for c, r in run.roles[s.name].items() if r == "id"]
    values = {(n, c): [_cell(r.get(c)) for r in run.by_name[n].rows] for n, c in cols}
    masked = {(n, c): [_cell(r.get(c)) for r in run.out[n]] for n, c in cols}
    pairs, done = [], set()
    for a in cols:
        for b in cols:
            if a[0] == b[0] or (b, a) in done:
                continue
            va, vb = {v for v in values[a] if v}, {v for v in values[b] if v}
            if not va or not vb or max(len(va & vb) / len(va), len(va & vb) / len(vb)) < JOIN_OVERLAP:
                continue
            done.add((a, b))
            # The referencing side is the one with more rows per value (orders -> customers).
            ref, key = (a, b) if len(values[a]) / len(va) >= len(values[b]) / len(vb) else (b, a)
            pairs.append(_join(ref, key, values, masked))
    refs = _text_refs(run, cols, values, masked)
    return {
        "measured": "every join between id columns of different inputs (found from overlapping original "
                    "values), row by row, plus ids in free text that name a row of a table",
        "not_measured": "joins on non-id columns (names, emails used as keys) and composite keys",
        "pairs": pairs, "text_refs": refs,
        "checked": sum(p["checked"] for p in pairs) + refs["checked"],
        "broken": sum(p["broken"] for p in pairs) + refs["broken"],
        "spurious": sum(p["spurious"] for p in pairs),
    }


def _join(ref: tuple, key: tuple, values: dict, masked: dict) -> dict:
    before, after = defaultdict(set), defaultdict(set)
    for j, v in enumerate(values[key]):
        before[v].add(j)
    for j, v in enumerate(masked[key]):
        after[v].add(j)
    checked = broken = spurious = 0
    for v, w in zip(values[ref], masked[ref]):
        if not v:
            continue
        if v in before:
            checked += 1
            broken += after.get(w) != before[v]
        elif w in after:
            spurious += 1
    return {"from": ".".join(ref), "to": ".".join(key), "checked": checked, "broken": broken, "spurious": spurious}


def _text_refs(run: Run, cols: list, values: dict, masked: dict) -> dict:
    """An id in free text that equals a table's id must have become that table's masked id."""
    strip = lambda s: s.strip().lstrip("#").strip(" .,;:")
    expected: dict[str, set[str]] = defaultdict(set)
    for col in cols:
        for v, w in zip(values[col], masked[col]):
            if v:
                expected[strip(v)].add(strip(w))
    checked = broken = 0
    for m in run.mentions:
        if m.start is None or m.category != "ID":
            continue
        original = strip(run.original(m))
        if original in expected:
            checked += 1
            broken += strip(run.masked(m)) not in expected[original]
    return {"checked": checked, "broken": broken}


def date_gaps(run: Run) -> dict:
    """Each person's dates move together: the gap between any two of them is unchanged."""
    groups: dict[str | None, list[tuple]] = defaultdict(list)
    unparsed = no_year = 0
    for m in run.mentions:
        if m.category != "DATE" or m.label not in DATE_LABELS or not m.changed:
            continue
        original = run.original(m)
        a, b = parse_date(original), parse_date(run.masked(m))
        if a is None or b is None:
            unparsed += 1
            continue
        if a.year == 2000 and "00" not in original:  # 'March 7' with no year: gaps across New Year are lost
            no_year += 1
            continue
        groups[m.persona].append((a, b))
    pairs = exact = worst = 0
    for dates in groups.values():
        a0, b0 = dates[0]
        for a, b in dates[1:]:
            error = abs((b - b0).days - (a - a0).days)
            pairs += 1
            exact += error == 0
            worst = max(worst, error)
    return {
        "measured": "every shifted date (columns and text) grouped by the person it belongs to; for each "
                    "person, the gap from their first date to each other date, before and after",
        "not_measured": f"birth dates (regenerated within the persona's birth year by design); "
                        f"{no_year} dates written without a year; {unparsed} dates that did not parse",
        "people": sum(len(d) > 1 for k, d in groups.items() if k), "pairs": pairs, "exact": exact,
        "exact_share": _share(exact, pairs), "max_error_days": worst, "no_year": no_year, "unparsed": unparsed,
    }


def _number(value: object) -> float | None:
    if isinstance(value, bool) or missing(value):
        return None
    try:
        return float(str(value).replace(",", "").lstrip("$"))
    except ValueError:
        return None


def tvd(a: list, b: list) -> float:
    """Total variation distance between two samples' value frequencies, 0 (same) to 1 (disjoint)."""
    pa, pb = Counter(a), Counter(b)
    return 0.5 * sum(abs(pa[k] / len(a) - pb[k] / len(b)) for k in pa.keys() | pb.keys())


def ks(a: list[float], b: list[float]) -> float:
    """Two-sample Kolmogorov-Smirnov statistic: the largest gap between the two empirical CDFs."""
    a, b = sorted(a), sorted(b)
    i = j = 0
    worst = 0.0
    while i < len(a) and j < len(b):
        x = min(a[i], b[j])
        while i < len(a) and a[i] == x:
            i += 1
        while j < len(b) and b[j] == x:
            j += 1
        worst = max(worst, abs(i / len(a) - j / len(b)))
    return worst


def _series(role: str, values: list) -> tuple[str, list] | None:
    """The test that fits a column, and the values it compares, or None to skip the column."""
    present = [v for v in values if not missing(v)]
    if not present:
        return None
    if role in ("age",) or role == "keep" and all(_number(v) is not None for v in present):
        return "ks", [_number(v) for v in present if _number(v) is not None]
    if role in ("dob", "date"):
        days = [parse_date(str(v)) for v in present]
        days = [d for d in days if d]
        return ("ks", [d.year if role == "dob" else d.toordinal() for d in days]) if days else None
    if role in ("sex", "state") or (role == "keep" and len({str(v) for v in present}) <= CATEGORICAL_MAX):
        return "tvd", [str(v).strip().casefold() for v in present]
    return None


def distributions(run: Run) -> dict:
    columns = []
    for src in run.sources:
        if src.kind != "table":
            continue
        for col, role in run.roles[src.name].items():
            before = _series(role, [r.get(col) for r in src.rows])
            after = _series(role, [r.get(col) for r in run.out[src.name]])
            if before is None or after is None or not before[1] or not after[1]:
                continue
            test = before[0]
            value = ks(before[1], after[1]) if test == "ks" else tvd(before[1], after[1])
            columns.append({"table": src.name, "column": col, "role": role, "test": test, "value": round(value, 4),
                            "what": "birth year" if role == "dob" else "day" if role == "date" else None})
    return {
        "measured": "per table column, the distance between the original and masked value distributions: "
                    "total variation (TVD) for categories, Kolmogorov-Smirnov (KS) for numbers, dates (by day) "
                    "and birth dates (by year); 0 is identical, 1 disjoint",
        "not_measured": "joint distributions across columns; columns of unique keys and free text (names, "
                        "emails, ids), where a distribution distance means nothing",
        "columns": columns,
    }


FORMAT_CHECKS = {
    "email": lambda v: bool(rules.EMAIL.fullmatch(v)),
    "phone": lambda v: bool(rules.PHONE.fullmatch(v)) or len(re.sub(r"\D", "", v)) in (7, 10, 11),
    "date": lambda v: parse_date(v) is not None,
    "card": lambda v: 13 <= len(d := re.sub(r"\D", "", v)) <= 19 and luhn_ok(d),
    "ssn": lambda v: bool(re.fullmatch(r"\d{3}-?\d{2}-?\d{4}", v)),
    "zip": lambda v: bool(re.fullmatch(r"\d{5}(?:-\d{4})?", v)),
}


def _format_kind(m, original: str) -> str | None:
    label = m.label
    if label == "email" or (m.category == "CONTACT" and "@" in original):
        return "email"
    if label == "phone":
        return "phone"
    if label in ("date", "dob", "birth_date"):
        return "date"
    if label == "zip" and m.start is None:
        return "zip"
    if label in ("card_number", "financial") and 13 <= len(re.sub(r"\D", "", original)) <= 19:
        return "card"
    if label == "ssn":
        return "ssn"
    return None


def formats(run: Run) -> dict:
    """Replaced values keep a usable format: only values whose original passed the check are counted."""
    checked, valid = Counter(), Counter()
    for m in run.mentions:
        if not m.changed:
            continue
        original = run.original(m).strip()
        kind = _format_kind(m, original)
        if kind is None or not FORMAT_CHECKS[kind](original):
            continue
        new = run.masked(m).strip()
        ok = FORMAT_CHECKS[kind](new) and (kind != "date" or m.start is not None or not is_date(original) or is_date(new))
        checked[kind] += 1
        valid[kind] += ok
    kinds = {k: {"checked": checked[k], "valid": valid[k], "share": _share(valid[k], checked[k])} for k in sorted(checked)}
    total = sum(checked.values())
    return {
        "measured": "replaced emails, phones, dates, ZIPs, card numbers (Luhn) and SSNs whose original parsed: "
                    "does the replacement still parse",
        "not_measured": "whether a value is real-world deliverable (an email inbox, a dialable number) — "
                        "replacements use reserved domains and fictional ranges on purpose",
        "kinds": kinds, "checked": total, "valid": sum(valid.values()), "share": _share(sum(valid.values()), total),
    }


def placeholders(run: Run) -> dict:
    changed = [m for m in run.mentions if m.changed]
    n = sum(bool(PLACEHOLDER.search(run.masked(m))) for m in changed)
    return {"measured": "replacements that are placeholders ([PERSON], ***, REDACTED) rather than values",
            "replaced": len(changed), "placeholders": n, "share": _share(n, len(changed))}


def non_pii(run: Run) -> dict:
    """Over-masking without gold: text outside replaced spans, and cells of kept columns, unchanged."""
    spans: dict[tuple, list] = defaultdict(list)
    for m in run.mentions:
        if m.start is not None:
            spans[(m.source, m.row, m.column)].append(m)
    chars = changed_chars = cells = changed_cells = 0
    for src in run.sources:
        for i, (row, new) in enumerate(zip(src.rows, run.out[src.name])):
            for col, role in run.roles[src.name].items():
                if role == "text" and isinstance(row.get(col), str):
                    ms = sorted(spans.get((src.name, i, col), ()), key=lambda m: m.start)
                    before = _outside(row[col], [(m.start, m.end) for m in ms])
                    after = _outside(_cell(new.get(col)), [(m.out_start, m.out_end) for m in ms])
                    chars += len(before)
                    changed_chars += sum(x != y for x, y in zip(before, after)) + abs(len(before) - len(after))
                elif role in ("keep", "sex"):
                    cells += 1
                    changed_cells += _cell(row.get(col)) != _cell(new.get(col))
    return {
        "measured": "characters of free text outside every replaced span, and cells of columns kept as they "
                    "are (role keep or sex): how many changed",
        "not_measured": "spans a detector replaced that were not personal data (a product named like a person): "
                        "that needs gold labels",
        "text_chars": chars, "text_chars_changed": changed_chars, "kept_cells": cells,
        "kept_cells_changed": changed_cells, "share": _share(changed_chars + changed_cells, chars + cells),
    }


def _outside(text: str, spans: list[tuple[int, int]]) -> str:
    out, pos = [], 0
    for a, b in spans:
        out.append(text[pos:a])
        pos = b
    out.append(text[pos:])
    return "".join(out)

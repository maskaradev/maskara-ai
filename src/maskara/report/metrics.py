"""Report metrics that need no gold labels (v0-design §4.1–4.2), computed from one run.

They run inside `mask()`, where the original rows are still in memory. Originals are read to compare
against the output and are never copied into what these functions return: counts, shares, column
names and locations (input, row, column), not values.

Every metric says what it measured and what it could not (`measured`, `not_measured`), because a
zero only means something next to its scope: "0 originals found" covers the values the detectors and
column roles knew about, not PII nobody found.
"""

from __future__ import annotations


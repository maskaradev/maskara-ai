"""`maskara demo`: mask the bundled store dataset and show what changed, offline, in a few seconds.

The data (src/maskara/data/demo) is synthetic: people from Nemotron-Personas-USA (CC BY 4.0), the
rest generated by `maskara.data.build_demo`. It runs with a public seed and no model, so every run
prints the same thing.
"""

from __future__ import annotations

import csv
import re
import textwrap
import time
from pathlib import Path

from .api import MaskResult, mask
from .report import headline_lines
from .vault import Vault

DATA = Path(__file__).parent / "data" / "demo"
SEED = "maskara"
TABLES = ("customers", "agents", "orders", "tickets")
SUBJECTS = {"customers": "customer_id", "orders": "customer_id", "tickets": "customer_id", "agents": "agent_id"}
SHOW_TICKET = 0  # an email that also mentions a second customer, a birth date and a card


def run(preset: str = "balanced") -> tuple[MaskResult, float]:
    started = time.perf_counter()
    result = mask(tables={t: DATA / f"{t}.csv" for t in TABLES}, texts={"notes": DATA / "notes.jsonl"},
                  subjects=SUBJECTS, preset=preset, vault=Vault.from_seed(SEED), detector="rules")
    return result, time.perf_counter() - started


def originals() -> list[str]:
    """Every customer's and agent's name, email and phone digits, to check none survive."""
    out = []
    for name in ("customers", "agents"):
        with (DATA / f"{name}.csv").open(newline="") as f:
            for r in csv.DictReader(f):
                out.append(f"{r['first_name']} {r['last_name']}")
                out += [r[k] for k in ("email",) if r.get(k)]
                out += [re.sub(r"\D", "", r["phone"])] if r.get("phone") else []
    return out


def leaks(result: MaskResult) -> list[str]:
    blob = "\n".join(str(v) for rows in result.tables.values() for r in rows for v in r.values())
    blob += "\n" + "\n".join(r["text"] for r in result.texts["notes"])
    lower, digits = blob.lower(), re.sub(r"\D", "", blob)
    return [o for o in originals() if (o in digits if o.isdigit() else o.lower() in lower)]


def _rows(name: str) -> list[dict]:
    with (DATA / f"{name}.csv").open(newline="") as f:
        return list(csv.DictReader(f))


def _indent(text: str) -> str:
    return textwrap.indent(text, "    │ ", lambda line: True)


def render(result: MaskResult, seconds: float) -> str:
    before_c, after_c = _rows("customers")[0], result.tables["customers"][0]
    fields = ("first_name", "last_name", "email", "phone", "birth_date", "street", "city", "state", "zip")
    width = max(len(f) for f in fields)
    lines = ["maskara demo: an online store's customers, orders, support tickets and agent notes",
             "(synthetic data bundled with maskara; public seed, no model, nothing leaves this machine)", "",
             "customers.csv, row 1"]
    lines += [f"    {f:<{width}}  {before_c[f]:<32} → {after_c[f]}" for f in fields]
    ticket_b, ticket_a = _rows("tickets")[SHOW_TICKET], result.tables["tickets"][SHOW_TICKET]
    lines += ["", f"tickets.csv, row {SHOW_TICKET + 1}, transcript before", _indent(ticket_b["transcript"]),
              "  after", _indent(ticket_a["transcript"])]
    s = result.summary()
    rows = ", ".join(f"{n} {k}" for k, n in s["rows"].items())
    cats = ", ".join(f"{k.lower()} {n}" for k, n in sorted(s["by_category"].items(), key=lambda kv: -kv[1]))
    linked = 100 * (s["text_names_linked_to_tables"] or 0)
    lines += ["", "summary",
              f"    inputs        {rows}",
              f"    replaced      {s['replaced']} values: {cats}",
              f"    kept          {s['kept_by_policy']} values the preset keeps (state, country)",
              f"    personas      {s['personas']}; names in free text linked to a table row: {linked:.1f}%",
              f"    took          {seconds:.1f}s, preset {s['preset']}, detectors: rules + known values", "",
              "report (measured against the originals in memory; full report: maskara demo --out masked/)"]
    lines += [f"    {label:<12}  {value}" for label, value in headline_lines(result.report.to_dict())]
    lines += ["",
              "Same customer, same persona in every table, transcript and note; order and ticket ids still join;",
              "each person's dates move together, so gaps between them are exact.",
              "See it side by side in the browser: maskara ui --demo"]
    return "\n".join(lines)
